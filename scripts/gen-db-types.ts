// pnpm gen:types: writes src/lib/supabase/database.types.ts from the local database, in the shape of
// `supabase gen types typescript`. (That command needs Docker; this one reads the local stack via psql.)
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const psql = "/opt/homebrew/opt/postgresql@17/bin/psql";
const q = (sql: string) => {
  const r = spawnSync(psql, ["-h", "localhost", "-p", "54322", "-d", "postgres", "-t", "-A", "-c", sql], { encoding: "utf8" });
  if (r.status) throw new Error(r.stderr);
  return JSON.parse(r.stdout.trim() || "[]");
};

interface Col { table: string; name: string; type: string; udt: string; nullable: boolean; hasDefault: boolean; generated: boolean }
const cols: Col[] = q(`
  select json_agg(json_build_object('table', table_name, 'name', column_name, 'type', data_type, 'udt', udt_name,
    'nullable', is_nullable = 'YES', 'hasDefault', column_default is not null, 'generated', is_generated = 'ALWAYS') order by table_name, ordinal_position)
  from information_schema.columns where table_schema = 'public' and table_name not in ('local_migrations')`);
const enums: { name: string; labels: string[] }[] = q(`
  select json_agg(json_build_object('name', t.typname, 'labels', (select json_agg(e.enumlabel order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid)))
  from pg_type t join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' and t.typtype = 'e'`);
const fks: { table: string; column: string; ref: string; refCol: string; name: string }[] = q(`
  select json_agg(json_build_object('table', c.conrelid::regclass::text, 'column', a.attname, 'ref', c.confrelid::regclass::text, 'refCol', fa.attname, 'name', c.conname))
  from pg_constraint c join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
  join pg_attribute fa on fa.attrelid = c.confrelid and fa.attnum = c.confkey[1]
  where c.contype = 'f' and c.connamespace = 'public'::regnamespace`);

const enumNames = new Set(enums.map((e) => e.name));
const tsType = (c: Col) => {
  if (enumNames.has(c.udt)) return `Database["public"]["Enums"]["${c.udt}"]`;
  if (["uuid", "text", "character varying", "character", "date", "timestamp with time zone", "timestamp without time zone"].includes(c.type)) return "string";
  if (["integer", "smallint", "bigint", "numeric", "real", "double precision"].includes(c.type)) return "number";
  if (c.type === "boolean") return "boolean";
  if (c.type === "jsonb" || c.type === "json") return "Json";
  throw new Error(`unmapped type ${c.type} (${c.table}.${c.name})`);
};

const tables = [...new Set(cols.map((c) => c.table))];
const tableBlock = (t: string) => {
  const tc = cols.filter((c) => c.table === t);
  const line = (c: Col, mode: "Row" | "Insert" | "Update") => {
    // Postgres reports generated columns as nullable; ours are built from NOT NULL columns, so they never are.
    const base = tsType(c) + (c.nullable && !c.generated ? " | null" : "");
    if (mode === "Row") return `          ${c.name}: ${base}`;
    if (c.generated) return `          ${c.name}?: never`;
    if (mode === "Update" || c.hasDefault || c.nullable) return `          ${c.name}?: ${base}`;
    return `          ${c.name}: ${base}`;
  };
  const rels = fks.filter((f) => (f.table === t || f.table === `public.${t}`) && !f.ref.startsWith("auth."))
    .map((f) => `          {\n            foreignKeyName: "${f.name}"\n            columns: ["${f.column}"]\n            isOneToOne: false\n            referencedRelation: "${f.ref.replace("public.", "")}"\n            referencedColumns: ["${f.refCol}"]\n          },`);
  return `      ${t}: {\n        Row: {\n${tc.map((c) => line(c, "Row")).join("\n")}\n        }\n        Insert: {\n${tc.map((c) => line(c, "Insert")).join("\n")}\n        }\n        Update: {\n${tc.map((c) => line(c, "Update")).join("\n")}\n        }\n        Relationships: [${rels.length ? "\n" + rels.join("\n") + "\n        " : ""}]\n      }`;
};

const out = `// Generated by scripts/gen-db-types.ts from the migrations in supabase/migrations. Do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
${tables.map(tableBlock).join("\n")}
    }
    Views: { [_ in never]: never }
    Functions: { [_ in never]: never }
    Enums: {
${enums.map((e) => `      ${e.name}: ${e.labels.map((l) => `"${l}"`).join(" | ")}`).join("\n")}
    }
    CompositeTypes: { [_ in never]: never }
  }
};

export type Tables<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Row"];
export type TablesInsert<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Update"];
export type Enums<T extends keyof Database["public"]["Enums"]> = Database["public"]["Enums"][T];
`;
writeFileSync("src/lib/supabase/database.types.ts", out);
console.log(`Wrote database.types.ts (${tables.length} tables, ${enums.length} enums)`);
