const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const q = (s: string) => (s === "" ? "*(removed)*" : "“" + cell(s.trim()) + "”");

function table(rows: [string, string, string][]) {
  return ["| Location | Old text | New text |", "|---|---|---|", ...rows.map(([l, o, n]) => `| ${l} | ${o} | ${n} |`)].join("\n");
}

function rowsFor(n: 1 | 2 | 3): [string, string, string][] {
  const out: [string, string, string][] = [];
  for (const p of CORRECTIONS.filter((c) => c.correction === n)) out.push([p.location, q(p.old), q(p.new)]);
  for (const p of STRUCT_CORRECTIONS.filter((c) => c.correction === n)) {
    const flat = (v: unknown): string => (v as unknown[]).map((x) => (typeof x === "string" ? x : "em" in (x as object) ? ((x as { em: string[] }).em).join("") : "")).join("");
    out.push([p.location, q(flat(p.old)), q(flat(p.new))]);
  }
  for (const p of KIT_PATCHES.filter((c) => c.correction === n))
    out.push([p.location, typeof p.old === "string" ? q(p.old) : (p.oldDesc ?? "(pattern)"), p.newDesc ?? q(p.new)]);
  return out;
}

