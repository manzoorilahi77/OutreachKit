// Renders docs/roles.md from the permission map. `pnpm roles:doc` writes it; tests/roles.doc.test.ts fails if it is stale.
import { ROLES, ROLE_HOMES, ROLE_LABELS, canManage } from "./roles";
import { PERMISSIONS, PERMISSION_GROUPS, grantOf, type Grant, type Limit } from "./permissions";

const LIMIT_TEXT: Record<Limit, string> = {
  read: "read only",
  totals: "totals only",
  to_qualified: "up to Qualified",
  accounts: "+ accounts",
  not_super_admin: "except the Super Admin's",
};

const cell = (g: Grant) => (g.scope === "none" ? "—" : g.limit ? `${g.scope} (${LIMIT_TEXT[g.limit]})` : g.scope);

export function renderRolesDoc(): string {
  const out: string[] = [];
  out.push("# Roles and permissions", "");
  out.push("Generated by `pnpm roles:doc` from `src/lib/auth/permissions.ts`. Do not edit by hand.");
  out.push("Source of truth: `docs/source/roles-system.html`.", "");
  out.push("Logins identify people; they do not protect data. This map decides what the app shows and allows, not what is on disk.", "");

  out.push("## Roles", "", "| Role | Key | Home |", "|---|---|---|");
  for (const r of ROLES) out.push(`| ${ROLE_LABELS[r]} | \`${r}\` | \`${ROLE_HOMES[r]}\` |`);

  out.push("", "## Scopes", "");
  out.push("- `all`: everything in the workspace", "- `below`: roles below admin", "- `team`: their team", "- `own`: their own", "- `queue`: into the unassigned queue", "- `—`: no access");

  out.push("", "## Who can do what", "");
  for (const group of PERMISSION_GROUPS) {
    out.push(`### ${group}`, "", `| Action | Key | ${ROLES.map((r) => ROLE_LABELS[r]).join(" | ")} |`, `|---|---|${ROLES.map(() => "---").join("|")}|`);
    for (const p of PERMISSIONS.filter((x) => x.group === group)) {
      out.push(`| ${p.label} | \`${p.key}\` | ${ROLES.map((r) => cell(grantOf(r, p.key))).join(" | ")} |`);
    }
    out.push("");
  }

  out.push("## Who can act on whom", "", "Create, reset password, suspend, disable, enable, change role, move team. Nobody acts on themselves except to change their own password.", "");
  out.push(`| Acting role | ${ROLES.map((r) => ROLE_LABELS[r]).join(" | ")} |`, `|---|${ROLES.map(() => "---").join("|")}|`);
  for (const a of ROLES) out.push(`| ${ROLE_LABELS[a]} | ${ROLES.map((t) => (canManage(a, t) ? "yes" : "—")).join(" | ")} |`);

  return out.join("\n") + "\n";
}
